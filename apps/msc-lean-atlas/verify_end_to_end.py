#!/usr/bin/env python3
"""Exercise the actual HTTP API and Lean, without mocked responses."""
import argparse
from datetime import datetime,timezone
import json
from pathlib import Path
import time
import urllib.request

ROOT=Path(__file__).resolve().parent

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--url',default='http://127.0.0.1:8765');args=p.parse_args()
    def api(path,payload=None):
        body=json.dumps(payload).encode() if payload is not None else None
        request=urllib.request.Request(args.url+path,data=body,headers={'Content-Type':'application/json'} if body else {})
        with urllib.request.urlopen(request,timeout=30) as response:return json.load(response)
    def job(path,payload):
        request=api(path,payload);start=time.monotonic();last=None
        while time.monotonic()-start<900:
            state=api('/api/jobs/'+request['job_id'])
            status=(state['status'],state.get('progress'))
            if status!=last:print(json.dumps({'job':request['job_id'],'status':status},ensure_ascii=False),flush=True);last=status
            if state['status']=='complete':return state['result']
            if state['status']=='failed':raise RuntimeError(state.get('error'))
            time.sleep(1)
        raise TimeoutError('HTTP job did not finish within 15 minutes')
    graph=api('/api/graph');examples={e['id']:e for e in api('/api/examples')}
    assert len(graph['nodes'])==graph['meta']['counts']['nodes']
    assert len(graph['edges'])==graph['meta']['counts']['edges']
    report={'checked_at':datetime.now(timezone.utc).isoformat(),'mocked':False,'dataset_counts':graph['meta']['counts'],'cases':[]}
    # Published project correspondence, genuinely checked against both uploaded adapters.
    example=examples['astra-energy'];analysis=job('/api/analyze',example)
    assert analysis['inspection']['semantic_extraction'],analysis['inspection'].get('error')
    assert all(f['inspection_status']=='compiled' for f in analysis['files'])
    assert [f['msc_matches'][0]['code'] for f in analysis['files']]==['17C40','05C50']
    assert any(c['id']=='literature-P1' and c['status']=='candidate' for c in analysis['candidates'])
    verified=job('/api/verify',{'analysis_id':analysis['id'],'bridge_source':analysis['bridge_source'],'bridge_targets':analysis['bridge_targets']})
    assert verified['success'],verified
    report['cases'].append({'name':'astra-energy','analysis_id':analysis['id'],'inspection':'compiled','candidate_count':len(analysis['candidates']),'taxonomy_paths':analysis['taxonomy_paths'],'verification':verified})
    # The bridge is generated by the local analyzer; no prepared bridge file is supplied.
    example=examples['definition-equality'];example['context']['mathlib']='';example['context']['project_root']=''
    generated=job('/api/analyze',example)
    assert generated['bridge_origin']=='generated_definition_equality_attempt'
    proof=job('/api/verify',{'analysis_id':generated['id'],'bridge_source':generated['bridge_source'],'bridge_targets':generated['bridge_targets']})
    assert proof['success'],proof
    # A new incomplete proof must invalidate the successful current status.
    rejected=job('/api/verify',{'analysis_id':generated['id'],'bridge_source':generated['bridge_source'].replace('  rfl','  sorry'),'bridge_targets':generated['bridge_targets']})
    assert rejected['status']=='rejected' and rejected['success'] is False,rejected
    stored=api('/api/runs/'+generated['id'])
    assert stored['verification']['success'] is False
    report['cases'].append({'name':'definition-equality','analysis_id':generated['id'],'bridge_origin':generated['bridge_origin'],'verification_before_edit':proof,'verification_after_edit':rejected,'stale_success_prevented':True})
    report['success']=True;report['finished_at']=datetime.now(timezone.utc).isoformat()
    target=ROOT/'verification/end-to-end.json';target.parent.mkdir(exist_ok=True)
    target.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'success':True,'report':str(target),'analysis_id':analysis['id']},ensure_ascii=False),flush=True)

if __name__=='__main__':main()
