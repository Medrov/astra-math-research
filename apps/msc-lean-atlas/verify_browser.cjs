const {chromium}=require(process.env.ATLAS_PLAYWRIGHT_MODULE || 'playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
 const run=process.argv[2];if(!run)throw Error('Pass an actual saved analysis id');
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1500,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const root=path.join(__dirname,'verification');fs.mkdirSync(root,{recursive:true});
 await page.goto('http://127.0.0.1:8765/?run='+run+'#lean');
 await page.locator('#verification-result h3').filter({hasText:'Текущая связующая теорема проверена Lean'}).waitFor({timeout:30000});
 const report={mocked:false,analysis_id:run,errors,checks:[]};
 if(!(await page.locator('#file-content-0').inputValue()).includes('AlgebraObject'))throw Error('Input A not restored');
 if(!(await page.locator('#file-content-1').inputValue()).includes('GraphObject'))throw Error('Input B not restored');
 if(await page.locator('#msc-override-0').inputValue()!=='17C40')throw Error('MSC label not restored');
 if(!(await page.locator('#bridge-source').inputValue()).includes('energy_correspondence'))throw Error('Bridge not restored');
 if(!(await page.locator('#candidate-list').innerText()).includes('Ассоциатор'))throw Error('Published candidate not shown');
 report.checks.push('real saved source/context/targets/MSC/Bridge restored','actual Lean success displayed','actual candidate cards displayed');
 await page.locator('#verification-result').screenshot({path:path.join(root,'verified-project-bridge.png')});
 await page.locator('[data-tab="map"]').click();
 await page.locator('#graph-title').filter({hasText:'MSC2020'}).waitFor();
 await page.screenshot({path:path.join(root,'full-msc-overview.png'),fullPage:true});
 await page.locator('#msc-search').fill('05C50');
 await page.locator('#catalog-list button').first().click();
 await page.locator('#category-panel').getByText('Graphs and linear algebra (matrices, eigenvalues, etc.)',{exact:false}).first().waitFor();
 report.checks.push('real full graph overview','category code search and selection');
 await page.locator('[data-tab="lean"]').click();
 await page.locator('#bridge-source').fill((await page.locator('#bridge-source').inputValue())+'\n-- modified in browser QA\n');
 if(await page.locator('#verification-result h3').count())throw Error('Old success remained after bridge edit');
 report.checks.push('editing bridge clears old success');
 await page.setViewportSize({width:390,height:900});
 report.mobile_overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(report.mobile_overflow)throw Error('Mobile layout overflows');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync(path.join(root,'browser-real.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
